import { useEffect, useMemo, useRef, useState } from "react";
import { Link, useNavigate, useSearchParams } from "react-router-dom";
import {
  ArrowUpRight,
  ArrowsLeftRight,
  CheckCircle,
  Copy,
  Eye,
  FileAudio,
  FileText,
  Microphone,
  Pause,
  Play,
  Repeat,
  ShieldCheck,
  SpeakerHigh,
  Sparkle,
  TrendUp,
  VideoCamera,
  Warning,
  Waveform,
} from "@phosphor-icons/react";
import { Button, Card, Empty, ErrorBox, Loading, cx } from "@/components/ui";
import { api } from "@/lib/api";
import { useApi } from "@/lib/hooks";

export default function AudioForensicsPage() {
  const nav = useNavigate();
  const [searchParams] = useSearchParams();
  const initialId = Number(searchParams.get("id")) || null;

  const { data: audioData, error, loading, reload } = useApi(() => api.audioForensics(), []);

  const [selectedId, setSelectedId] = useState<number>(initialId || 6); // Default to voice_synthetic_tts_elevenlabs.wav
  const [isPlaying, setIsPlaying] = useState(false);
  const [currentTime, setCurrentTime] = useState(0);
  const [playbackSpeed, setPlaybackSpeed] = useState<number>(1);
  const [isLooping, setIsLooping] = useState(false);
  const [activeTab, setActiveTab] = useState<"spectrogram" | "formants" | "enf">("spectrogram");

  // Selected Item
  const activeItem = useMemo(() => {
    if (!audioData?.items) return null;
    return audioData.items.find((it: any) => it.id === selectedId) || audioData.items[0];
  }, [audioData, selectedId]);

  // Audio Playback simulation
  const duration = activeItem?.duration || 24.5;

  useEffect(() => {
    let interval: any = null;
    if (isPlaying) {
      interval = setInterval(() => {
        setCurrentTime((prev) => {
          if (prev >= duration) {
            if (isLooping) return 0;
            setIsPlaying(false);
            return 0;
          }
          return prev + 0.1 * playbackSpeed;
        });
      }, 100);
    }
    return () => clearInterval(interval);
  }, [isPlaying, playbackSpeed, isLooping, duration]);

  if (loading && !audioData) return <Loading label="Synthesizing Acoustic Spectrogram Matrix..." />;
  if (error && !audioData) return <ErrorBox message={error} onRetry={reload} />;
  if (!loading && (!audioData || !audioData.items || audioData.items.length === 0 || !activeItem)) {
    return (
      <div className="space-y-4 pb-12">
        <div>
          <div className="text-[10px] font-bold text-muted flex items-center gap-1.5">
            <SpeakerHigh size={14} className="text-accent" weight="fill" />
            Voice check
          </div>
          <h1 className="text-xl sm:text-2xl font-bold text-ink mt-0.5">
            Acoustic Forensics Studio
          </h1>
          <p className="text-xs text-muted mt-0.5">
            Voice authenticity, synthetic voice detection, and acoustic checks
          </p>
        </div>
        <Card className="p-8">
          <Empty
            title="No audio evidence found"
            hint="Upload audio recordings (WAV, MP3, M4A) to a case to inspect acoustic spectrograms and detect synthetic voice clones."
            action={<Link to="/cases"><Button variant="primary">Go to Cases</Button></Link>}
          />
        </Card>
      </div>
    );
  }

  const formatTime = (secs: number) => {
    const m = Math.floor(secs / 60);
    const s = Math.floor(secs % 60);
    const ms = Math.floor((secs % 1) * 10);
    return `${m.toString().padStart(2, "0")}:${s.toString().padStart(2, "0")}.${ms}`;
  };

  const isSynthetic = activeItem?.deepfake_analysis?.is_synthetic;

  return (
    <div className="space-y-6 pb-12">
      {/* Page Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-3">
        <div>
          <div className="text-[10px] font-bold text-muted flex items-center gap-1.5">
            <SpeakerHigh size={14} className="text-accent" weight="fill" />
            Voice check studio
          </div>
          <h1 className="text-xl sm:text-2xl font-bold text-ink mt-0.5">
            Voice Check
          </h1>
          <p className="text-xs text-muted mt-0.5">
            Check if a voice recording is genuine or generated by an AI voice tool.
          </p>
        </div>
      </div>

      {/* Exhibit Selector Bar */}
      <Card className="card-bento p-3 sm:p-4">
        <div className="flex items-center justify-between gap-3 mb-2">
          <span className="text-[11px] font-bold text-muted">
            Audio files ({audioData?.items?.length || 0}):
          </span>
          <span className="text-xs text-muted">Click any file to check it</span>
        </div>

        <div className="flex items-center gap-2 overflow-x-auto pb-1 pt-1">
          {audioData?.items?.map((it: any) => {
            const isSelected = it.id === (activeItem?.id || selectedId);
            const isSynth = it.deepfake_analysis?.is_synthetic;
            return (
              <button
                key={it.id}
                onClick={() => {
                  setSelectedId(it.id);
                  setCurrentTime(0);
                  setIsPlaying(false);
                }}
                className={cx(
                  "flex items-center gap-2 px-3 py-2 rounded-xl border text-xs font-semibold transition cursor-pointer shrink-0 max-w-[240px]",
                  isSelected
                    ? "bg-accent text-white border-accent shadow-xs"
                    : "bg-surface2/60 border-line text-muted hover:text-ink hover:bg-surface2"
                )}
              >
                <span
                  className={cx(
                    "size-2 rounded-full shrink-0",
                    isSelected ? "bg-white" : isSynth ? "bg-rose-500" : "bg-emerald-500"
                  )}
                />
                <span className="truncate">{it.filename}</span>
              </button>
            );
          })}
        </div>
      </Card>

      {/* Main Studio Console Layout */}
      {loading && !audioData ? (
        <Loading label="Synthesizing Acoustic Spectrogram Matrix..." />
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-5">
          {/* Left 8 Cols: Waveform Player & High-Res Spectrogram Stage */}
          <div className="lg:col-span-8 space-y-4">
            {/* Interactive Audio Waveform Player Stage */}
            <Card className="card-bento p-5 space-y-4">
              {/* Player Top Controls */}
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-line">
                <div className="flex items-center gap-3">
                  <button
                    onClick={() => setIsPlaying(!isPlaying)}
                    className="size-11 rounded-lg bg-accent text-white grid place-items-center shadow-md hover:bg-accent/90 transition cursor-pointer shrink-0"
                  >
                    {isPlaying ? <Pause size={20} weight="fill" /> : <Play size={20} weight="fill" className="ml-0.5" />}
                  </button>

                  <div>
                    <h3 className="text-sm font-bold text-ink truncate max-w-sm">
                      {activeItem?.filename}
                    </h3>
                    <div className="flex items-center gap-2 mt-0.5 font-mono text-xs text-muted">
                      <span className="font-bold text-accent">{formatTime(currentTime)}</span>
                      <span>/</span>
                      <span>{formatTime(duration)}</span>
                      <span>·</span>
                      <span>{activeItem?.sample_rate} Hz</span>
                    </div>
                  </div>
                </div>

                {/* Speed & Loop Controls */}
                <div className="flex items-center gap-2">
                  <button
                    onClick={() => setIsLooping(!isLooping)}
                    className={cx(
                      "size-8 rounded-xl border grid place-items-center text-xs transition cursor-pointer",
                      isLooping ? "bg-accent/10 border-accent text-accent" : "border-line text-muted hover:text-ink"
                    )}
                    title="Loop Playback"
                  >
                    <Repeat size={14} weight="bold" />
                  </button>

                  <div className="flex items-center rounded-xl border border-line bg-surface2/60 p-0.5 text-xs font-bold">
                    {[0.5, 1, 1.5, 2].map((spd) => (
                      <button
                        key={spd}
                        onClick={() => setPlaybackSpeed(spd)}
                        className={cx(
                          "rounded-lg px-2 py-0.5 transition cursor-pointer",
                          playbackSpeed === spd ? "bg-accent text-white" : "text-muted hover:text-ink"
                        )}
                      >
                        {spd}x
                      </button>
                    ))}
                  </div>
                </div>
              </div>

              {/* Animated Waveform Display */}
              <div className="relative h-28 w-full rounded-lg bg-surface2/40 border border-line/70 p-3 flex items-end gap-1 overflow-hidden select-none">
                {/* Progress playhead line */}
                <div
                  className="absolute top-0 bottom-0 w-0.5 bg-accent z-20 shadow-[0_0_8px_rgba(59,59,245,0.8)]"
                  style={{ left: `${(currentTime / duration) * 100}%` }}
                />

                {/* Waveform Bars */}
                {activeItem?.waveform_peaks?.map((val: number, idx: number) => {
                  const pct = (idx / 64) * duration;
                  const isPlayed = pct <= currentTime;
                  const isTamperZone = isSynthetic && idx >= 20 && idx <= 38;

                  return (
                    <div
                      key={idx}
                      onClick={() => setCurrentTime(pct)}
                      className="flex-1 flex flex-col justify-end items-center h-full cursor-pointer group"
                    >
                      <div
                        className={cx(
                          "w-full rounded-full transition-all duration-75",
                          isTamperZone
                            ? "bg-rose-500 group-hover:bg-rose-400"
                            : isPlayed
                            ? "bg-accent group-hover:bg-accent/80"
                            : "bg-line hover:bg-muted"
                        )}
                        style={{ height: `${Math.max(10, val * 100)}%` }}
                      />
                    </div>
                  );
                })}

                {/* Tamper Marker Overlay Label */}
                {isSynthetic && (
                  <div className="absolute top-2 left-[34%] rounded-full bg-rose-500/15 border border-rose-500/40 px-2 py-0.5 font-mono text-[9px] font-bold text-rose-600">
                    Unnatural edited section
                  </div>
                )}
              </div>
            </Card>

            {/* High-Resolution FFT Spectrogram Heatmap */}
            <Card className="card-bento p-5 space-y-3">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                <div className="flex items-center gap-2">
                  <Waveform size={18} className="text-accent" weight="bold" />
                  <h3 className="text-sm font-bold text-ink">
                    Voice frequency chart (0 Hz - 8,000 Hz)
                  </h3>
                </div>

                <div className="flex items-center gap-2">
                  <span className="font-mono text-[10px] text-muted">
                    Color shows sound volume
                  </span>
                </div>
              </div>

              {/* The Spectrogram Canvas */}
              <div className="relative h-64 w-full rounded-lg overflow-hidden border border-line bg-[#0B0F1C] p-4 flex flex-col justify-between">
                {/* Simulated Spectrogram Heatmap Gradients */}
                <div className="absolute inset-0 bg-gradient-to-t from-[#0d1527] via-[#211134] to-[#0B0F1C]" />

                {/* Dynamic Spectrogram Frequency Wave Layers */}
                <svg className="absolute inset-0 w-full h-full opacity-80" preserveAspectRatio="none" viewBox="0 0 100 100">
                  <defs>
                    <linearGradient id="specGrad" x1="0" y1="1" x2="0" y2="0">
                      <stop offset="0%" stopColor="#4338CA" />
                      <stop offset="30%" stopColor="#8B5CF6" />
                      <stop offset="60%" stopColor="#F59E0B" />
                      <stop offset="85%" stopColor="#EF4444" />
                    </linearGradient>
                  </defs>

                  {/* Frequency energy paths */}
                  <path
                    d={isSynthetic 
                      ? "M 0,80 Q 20,40 40,65 T 70,85 L 100,85 L 100,100 L 0,100 Z"
                      : "M 0,60 Q 25,20 50,45 T 100,30 L 100,100 L 0,100 Z"}
                    fill="url(#specGrad)"
                    opacity="0.85"
                  />

                  {/* High Frequency Vocoder Cutoff Shelf Line for Deepfakes */}
                  {isSynthetic && (
                    <line
                      x1="0"
                      y1="35"
                      x2="100"
                      y2="35"
                      stroke="#EF4444"
                      strokeWidth="1.2"
                      strokeDasharray="2, 2"
                    />
                  )}
                </svg>

                {/* Scrubber playhead on Spectrogram */}
                <div
                  className="absolute top-0 bottom-0 w-0.5 bg-white/90 z-20 shadow-[0_0_8px_#ffffff]"
                  style={{ left: `${(currentTime / duration) * 100}%` }}
                />

                {/* Y-Axis Frequency Grid Labels */}
                <div className="relative z-10 flex flex-col justify-between h-full font-mono text-[9px] font-bold text-slate-400 pointer-events-none select-none">
                  <div className="flex items-center justify-between">
                    <span>8,000 Hz (High Air)</span>
                    {isSynthetic && (
                      <span className="rounded bg-rose-500/90 text-white px-1.5 py-0.5 text-[8.5px] font-extrabold shadow-xs">
                        Voice cuts off sharply (sign of AI fake)
                      </span>
                    )}
                  </div>
                  <div>4,000 Hz (Consonant Clarity)</div>
                  <div>2,000 Hz (Vocal Formant F2)</div>
                  <div>500 Hz (Fundamental Vocal F0)</div>
                  <div className="flex items-center justify-between">
                    <span>60 Hz (Sub-Bass)</span>
                    <span className="text-emerald-400 font-bold">50.018 Hz (ENF Grid Baseline)</span>
                  </div>
                </div>
              </div>

              {/* Spectrogram Annotations */}
              <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5 pt-1 text-xs">
                <div className="rounded-xl border border-line bg-surface2/40 p-2.5">
                  <span className="text-[10px] font-bold uppercase text-muted">Sound cutoff point</span>
                  <div className="font-mono font-bold text-ink mt-0.5">
                    {activeItem?.cutoff_hz} Hz
                  </div>
                </div>

                <div className="rounded-xl border border-line bg-surface2/40 p-2.5">
                  <span className="text-[10px] font-bold uppercase text-muted">Pitch changes</span>
                  <div className="font-mono font-bold text-ink mt-0.5">
                    &plusmn;{activeItem?.deepfake_analysis?.pitch_drift_stdev_hz} Hz ({isSynthetic ? "Unnatural" : "Human"})
                  </div>
                </div>

                <div className="rounded-xl border border-line bg-surface2/40 p-2.5">
                  <span className="text-[10px] font-bold uppercase text-muted">Voice tone peaks</span>
                  <div className="font-mono font-bold text-ink mt-0.5">
                    F1:{activeItem?.deepfake_analysis?.formants?.F1} · F2:{activeItem?.deepfake_analysis?.formants?.F2}
                  </div>
                </div>
              </div>
            </Card>
          </div>

          {/* Right 4 Cols: Deepfake Biometrics & Legal Compliance Report */}
          <div className="lg:col-span-4 space-y-4">
            {/* Deepfake Verdict Card */}
            <Card className="card-bento p-5 space-y-4">
              <div className="flex items-start justify-between">
                <div>
                  <span className="text-[10px] font-bold text-muted">
                    Voice check result
                  </span>
                  <h3 className="text-base font-extrabold text-ink mt-0.5">
                    {isSynthetic ? "Fake AI voice detected" : "Genuine human voice"}
                  </h3>
                </div>

                <span
                  className={cx(
                    "size-9 rounded-xl grid place-items-center",
                    isSynthetic ? "bg-rose-500/10 text-rose-600" : "bg-emerald-500/10 text-emerald-600"
                  )}
                >
                  {isSynthetic ? <Warning size={20} weight="fill" /> : <ShieldCheck size={20} weight="fill" />}
                </span>
              </div>

              {/* Confidence Gauge */}
              <div className="rounded-lg border border-line bg-surface2/40 p-3.5 space-y-2">
                <div className="flex items-center justify-between text-xs">
                  <span className="font-bold text-ink">Chance this voice is fake</span>
                  <span
                    className={cx(
                      "font-mono font-extrabold text-sm",
                      isSynthetic ? "text-rose-600" : "text-emerald-600"
                    )}
                  >
                    {activeItem?.deepfake_analysis?.synthetic_confidence}%
                  </span>
                </div>

                <div className="h-2.5 w-full rounded-full bg-line overflow-hidden">
                  <div
                    className={cx(
                      "h-full rounded-full transition-all duration-500",
                      isSynthetic ? "bg-rose-500" : "bg-emerald-500"
                    )}
                    style={{ width: `${activeItem?.deepfake_analysis?.synthetic_confidence}%` }}
                  />
                </div>
              </div>

              {/* Detected Architecture Signature */}
              <div className="space-y-1">
                <span className="text-[10px] font-bold text-muted">
                  Tool used to fake it:
                </span>
                <div className="rounded-xl border border-line bg-surface2/50 p-2.5 font-mono text-xs font-bold text-ink">
                  {activeItem?.deepfake_analysis?.model_detected}
                </div>
              </div>

              {/* ENF Grid Synchronization */}
              <div className="space-y-1">
                <span className="text-[10px] font-bold text-muted">
                  Power grid background hum:
                </span>
                <div className="rounded-xl border border-line bg-surface2/50 p-2.5 text-xs text-ink font-medium">
                  {activeItem?.deepfake_analysis?.enf_grid_match}
                </div>
              </div>

              {/* Forensic Anomalies List */}
              {activeItem?.deepfake_analysis?.anomalies?.length > 0 && (
                <div className="space-y-2 pt-1">
                  <span className="text-[10px] font-bold text-muted">
                    Things noticed in the voice:
                  </span>
                  <div className="space-y-2">
                    {activeItem.deepfake_analysis.anomalies.map((a: any, i: number) => (
                      <div key={i} className="rounded-xl border border-rose-500/30 bg-rose-500/5 p-2.5 text-xs space-y-1">
                        <div className="flex items-center justify-between font-mono font-bold text-rose-600 text-[11px]">
                          <span>{a.type}</span>
                          <span>@{a.time}</span>
                        </div>
                        <p className="text-[11px] text-muted leading-tight">
                          {a.detail}
                        </p>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Actions */}
              <div className="pt-2 flex items-center gap-2">
                <Button
                  variant="primary"
                  onClick={() => nav(`/evidence/${activeItem.id}`)}
                  className="flex-1 btn-pill text-xs py-2"
                >
                  <Eye size={14} weight="bold" />
                  <span>View Evidence Details</span>
                </Button>
              </div>
            </Card>
          </div>
        </div>
      )}
    </div>
  );
}
